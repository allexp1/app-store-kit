#!/usr/bin/env python3
"""Creative-director screenshot campaigns: concepts, panoramas, 3D devices, exact App Store exports.

Usage:
  campaign.py analyze SCREENSHOT... [--icon ICON] [--out analysis.json]
  campaign.py init KIT --app NAME --screens DIR [--icon ICON] [--panels 6] [--slot iphone-di-large]
  campaign.py check CAMPAIGN.yaml
  campaign.py concepts CAMPAIGN.yaml [--engines a,b,...] [--scale 0.3] [--locale L] [--slot S] [--out DIR]
  campaign.py render CAMPAIGN.yaml [--engine E] [--locale L]... [--slot S]... [--panel N] [--install KIT]
                                   [--out DIR] [--offline]
  campaign.py eject CAMPAIGN.yaml [--engine E] [--out FILE]
  campaign.py validate OUT_DIR
  campaign.py canvas CAMPAIGN.yaml --out DIR [--locale L] [--slot S]   (Claude Design canvas files)
  campaign.py canvas-link DIR                                           (after uploading DIR/assets.json)
  campaign.py engines | presets

Rendering needs a Chromium (the Playwright cache's chrome-headless-shell, or $CHROME). Fonts are open-licence
faces fetched once into ~/.cache/app-store-kit/fonts (or the owner's own files, referenced in place).
Nothing here talks to App Store Connect: `render --install KIT` copies validated panels into
KIT/screenshots/<locale>/<slot>/, where validate_kit.py and asc_sync.py (with its own approval) take over.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import tempfile

import yaml
from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from studio import analyze, engines, fonts, pipeline  # noqa: E402
from studio import spec as S  # noqa: E402


def load_rules(campaign_path=None):
    if campaign_path:
        for d in [pathlib.Path(campaign_path).resolve().parent, pathlib.Path(campaign_path).resolve().parent.parent]:
            if (d / "rules.json").exists():
                return json.loads((d / "rules.json").read_text())
    return json.loads((HERE / "rules.json").read_text())


def print_issues(issues, quiet_notes=True):
    for lvl, where, msg in issues:
        if lvl == "note" and quiet_notes:
            continue
        print(f"  {lvl.upper():5} {where}: {msg}")


def load_checked(path, rules, allow_warn=True):
    spec = S.load(path)
    issues = S.validate(spec, rules)
    errs = [i for i in issues if i[0] == "error"]
    print_issues(issues)
    if errs:
        raise SystemExit(f"{len(errs)} error(s) in {path}; fix them first")
    return spec, issues


def cmd_analyze(a):
    shots = [analyze.describe(pathlib.Path(p)) for p in a.screens]
    icon = analyze.describe(pathlib.Path(a.icon)) if a.icon else None
    out = {"screens": shots, "icon": icon, "palette": analyze.suggest_palette(shots, icon),
           "note": "Measurements only. Read the app (README, feature code, store copy) for what it does and who "
                   "it is for, and confirm the palette against the brand."}
    txt = json.dumps(out, indent=2)
    if a.out:
        pathlib.Path(a.out).write_text(txt)
        print(f"wrote {a.out}")
    else:
        print(txt)


def cmd_init(a):
    kit = pathlib.Path(a.kit)
    cdir = kit / "campaign"
    cdir.mkdir(parents=True, exist_ok=True)
    target = cdir / "campaign.yaml"
    if target.exists() and not a.force:
        raise SystemExit(f"{target} exists (use --force to overwrite)")
    shots = sorted(p for p in pathlib.Path(a.screens).iterdir() if p.suffix.lower() in (".png", ".jpg", ".jpeg"))
    if not shots:
        raise SystemExit(f"no screenshots in {a.screens}")
    desc = [analyze.describe(p) for p in shots]
    icon = analyze.describe(pathlib.Path(a.icon)) if a.icon else None
    rel = lambda p: str(pathlib.Path(p).resolve().relative_to(cdir.resolve())) if str(pathlib.Path(p).resolve()).startswith(str(cdir.resolve())) else str(pathlib.Path(p).resolve())  # noqa: E731
    screens = {p.stem.lower().replace(" ", "-"): rel(p) for p in shots}
    ids = list(screens)
    n = a.panels
    sb = []
    for i in range(n):
        sid = ids[i % len(ids)]
        sb.append({"id": S.ROLES[i] if i < len(S.ROLES) else f"p{i + 1}", "screen": sid,
                   "headline": {"en-US": "[HEADLINE: one benefit, 3-8 words]"},
                   "sub": {"en-US": "[optional supporting line]"}})
    doc = {
        "app": {"name": a.app, **({"icon": rel(a.icon)} if a.icon else {})},
        "campaign": {"name": f"{a.app} App Store campaign", "panels": n, "slots": [a.slot], "locales": ["en-US"],
                     "engine": "floating-3d", "seed": 7},
        "design": {"palette": analyze.suggest_palette(desc, icon), "type": {"preset": "modern-tech"}},
        "screens": screens,
        "storyboard": sb,
    }
    target.write_text("# Generated by campaign.py init. Replace every [PLACEHOLDER]; see references/creative-director.md\n"
                      + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110))
    print(f"wrote {target}: {len(shots)} screens, {n} panels. Next: write the storyboard copy, then `campaign.py concepts`.")


def placeholder_issues(spec):
    out = []
    for p in spec["storyboard"]:
        for f in ("headline", "sub", "kicker"):
            v = p.get(f)
            vals = list(v.values()) if isinstance(v, dict) else [v]
            if isinstance(v, list):          # an unquoted [PLACEHOLDER] reads as a YAML list
                vals = [f"[{x}]" for x in v]
            if any(isinstance(t, str) and "[" in t and "]" in t for t in vals):
                out.append(("error", f"storyboard {p['id']} {f}", "still a [PLACEHOLDER]"))
    return out


def cmd_check(a):
    rules = load_rules(a.campaign)
    spec = S.load(a.campaign)
    issues = S.validate(spec, rules) + placeholder_issues(spec)
    print_issues(issues, quiet_notes=False)
    errs = sum(1 for i in issues if i[0] == "error")
    print(f"{'FAIL' if errs else 'OK'}: {errs} error(s), {sum(1 for i in issues if i[0] == 'warn')} warning(s)")
    return 1 if errs else 0


def out_root(a, spec):
    return pathlib.Path(a.out) if a.out else pathlib.Path(spec["_base"]) / "out"


def concept_list(spec, wanted):
    if spec.get("concepts") and not wanted:
        return spec["concepts"]
    names = wanted or engines.DEFAULT_SIX
    return [{"engine": n} for n in names]


def cmd_concepts(a):
    rules = load_rules(a.campaign)
    base, _ = load_checked(a.campaign, rules)
    wanted = [x.strip() for x in a.engines.split(",")] if a.engines else None
    concepts = concept_list(base, wanted)
    locale = a.locale or base["campaign"]["primary_locale"]
    slot = S.slot_size(a.slot or base["campaign"]["slots"][0], rules)
    out = out_root(a, base) / "concepts"
    out.mkdir(parents=True, exist_ok=True)
    blocks = pipeline.screen_blocks(base, locale, slot[0])
    rendered = []
    for k, c in enumerate(concepts):
        eng = c["engine"]
        meta = engines.ENGINES[eng]
        spec = S.normalize(S.deep_merge({key: v for key, v in base.items() if not key.startswith("_")}, {}))
        spec["_base"], spec["_path"] = base["_base"], base["_path"]
        spec["design"]["type"] = {**spec["design"]["type"], "preset": c.get("type") or meta["type"]}
        if c.get("palette"):
            spec["design"]["palette"] = {**spec["design"]["palette"], **c["palette"]}
        spec["layers"] = None
        lay = pipeline.layout_for(spec, eng, blocks)
        letter = chr(ord("A") + k)
        with tempfile.TemporaryDirectory() as td:
            r = pipeline.render_master(spec, lay, locale, slot, pathlib.Path(td), scale=a.scale, offline=a.offline)
            prev = out / f"{letter}-{eng}.png"
            with Image.open(r["png"]) as im:
                pipeline.to_rgb(im).save(prev)
            qa = pipeline.qa(spec, r, slot)
        pv = fonts.PRESETS[spec["design"]["type"]["preset"]]
        pal = spec["design"]["palette"]
        rendered.append({"letter": letter, "engine": eng, "label": c.get("name") or meta["label"],
                         "mood": c.get("mood") or meta["mood"], "rationale": c.get("rationale", ""),
                         "pattern": meta["pattern"], "type": spec["design"]["type"]["preset"], "type_mood": pv["mood"],
                         "palette": pal, "palette_swatches": [pal[t] for t in ("bg", "bg2", "ink", "accent", "accent2", "dark") if t in pal],
                         "preview": str(prev), "needs": meta["needs"],
                         "qa": [list(i) for i in qa if i[0] != "note"]})
        print(f"{letter}  {eng:18} {prev}  ({sum(1 for i in qa if i[0] == 'error')} errors, "
              f"{sum(1 for i in qa if i[0] == 'warn')} warnings)")
    _, font_css, _ = fonts.resolve({"preset": "modern-tech"}, set(), pathlib.Path(base["_base"]), a.offline)
    sheet = pipeline.contact_sheet(rendered, out / "contact-sheet.png",
                                   f"{base['campaign']['name']}: creative directions", font_css=font_css)
    pipeline.write_json(out / "concepts.json", {"locale": locale, "slot": slot[0], "concepts": rendered})
    print(f"contact sheet: {sheet}")
    return 0


def cmd_render(a):
    rules = load_rules(a.campaign)
    spec, spec_issues = load_checked(a.campaign, rules)
    ph = placeholder_issues(spec)
    if ph:
        print_issues(ph)
        raise SystemExit("copy still has placeholders")
    root = out_root(a, spec)
    locales = a.locale or spec["campaign"]["locales"]
    slots = [S.slot_size(s, rules) for s in (a.slot or spec["campaign"]["slots"])]
    N = spec["campaign"]["panels"]
    ids = [p["id"] for p in spec["storyboard"]]
    manifest = {"campaign": spec["campaign"]["name"], "source": spec["_path"], "renders": [],
                "artwork": spec.get("artwork") or {}, "mockup_only": spec["campaign"]["mockup_only"]}
    mpath = root / "campaign-manifest.json"
    old = json.loads(mpath.read_text()) if mpath.exists() else {}
    worst = 0
    for loc in locales:
        for slot in slots:
            sid, W, H = slot
            blocks = pipeline.screen_blocks(spec, loc, sid)
            lay = pipeline.layout_for(spec, a.engine, blocks)
            d = root / loc / sid
            work = d / "source"
            r = pipeline.render_master(spec, lay, loc, slot, work, 1.0, a.offline)
            nt = pipeline.notext_pass(spec, lay, loc, slot, r, work)
            issues = pipeline.qa(spec, r, slot, nt)
            panels_dir = d / "panels"
            if a.panel:
                # MODE H: replace one panel, report any other panel the change touched
                with tempfile.TemporaryDirectory() as td:
                    tmp = pipeline.slice_panels(r["png"], N, W, H, r["mirror"], pathlib.Path(td) / "p", ids)
                    prev = {pathlib.Path(e["file"]).name: e["sha256"] for rr in old.get("renders", [])
                            if rr["locale"] == loc and rr["slot"] == sid for e in rr["files"]}
                    changed = [f.name for f in tmp if prev.get(f.name) and prev[f.name] != pipeline.sha(f)]
                    target = tmp[a.panel - 1]
                    panels_dir.mkdir(parents=True, exist_ok=True)
                    (panels_dir / target.name).write_bytes(target.read_bytes())
                    others = [c for c in changed if c != target.name]
                    if others:
                        issues.append(("warn", "regenerate", f"the edit also changed {', '.join(others)} (an "
                                                              "element crosses into them); re-render all to keep the seams"))
                files = sorted(panels_dir.glob("*.png"))
            else:
                if panels_dir.exists():
                    for f in panels_dir.glob("*.png"):
                        f.unlink()
                files = pipeline.slice_panels(r["png"], N, W, H, r["mirror"], panels_dir, ids)
                if not pipeline.reassemble_ok(files, r["png"], N, W, H, r["mirror"]):
                    issues.append(("error", "slicing", "panels do not reassemble into the master pixel for pixel"))
            issues += pipeline.export_checks(files, W, H, N)
            pipeline.presentation(files, d / "presentation.png", rtl=r["mirror"])
            pipeline.store_preview(files, d / "store-preview.png")
            lay_dump = {"engine": lay["engine"], "background": lay["background"], "layers": lay["layers"]}
            (work / "layout.yaml").write_text(yaml.safe_dump(lay_dump, sort_keys=False, allow_unicode=True))
            mine = [i for i in spec_issues if i[0] != "note" and (f"[{loc}]" in i[2] or f"{loc}:" in i[2]
                                                                   or f"for {loc}" in i[2] or not any(
                                                                       f"{x}" in i[2] for x in spec["campaign"]["locales"]))]
            errs = pipeline.write_report(d / "report.md", f"{spec['campaign']['name']} · {loc} · {sid}", issues + mine, [f"Engine: {lay['engine']}. Flow: {'mirrored (RTL)' if r['mirror'] else 'left to right'}.", ""])
            worst = max(worst, 1 if errs else 0)
            inst = None
            if a.install and not errs and not spec["campaign"]["mockup_only"]:
                dest, removed = pipeline.install(files, pathlib.Path(a.install), loc, sid)
                inst = str(dest)
                print(f"  installed into {dest}" + (f" (replaced {len(removed)})" if removed else ""))
            elif a.install:
                print("  not installed: " + ("mockup-only campaign" if spec["campaign"]["mockup_only"] else
                                             f"{errs} error(s), see {d / 'report.md'}"))
            manifest["renders"].append({"locale": loc, "slot": sid, "size": [W, H], "panels": N,
                                        "engine": lay["engine"], "mirrored": r["mirror"],
                                        "panorama": str(d / "panorama.png"), "files": pipeline.manifest_entry(files),
                                        "errors": errs, "warnings": sum(1 for i in issues if i[0] == "warn"),
                                        "fonts": {k: v for k, v in r["fonts"].items() if k in ("preset", "display", "text")},
                                        "installed": inst, "report": str(d / "report.md")})
            print(f"{loc} {sid}: {len(files)} panels, {errs} error(s) → {d}")
    pipeline.write_json(root / "design-tokens.json", S.tokens(spec))
    pipeline.write_json(mpath, manifest)
    print(f"manifest: {mpath}")
    return worst


def cmd_eject(a):
    rules = load_rules(a.campaign)
    spec, _ = load_checked(a.campaign, rules)
    loc = spec["campaign"]["primary_locale"]
    sid = S.slot_size(spec["campaign"]["slots"][0], rules)[0]
    eng = a.engine or spec["campaign"].get("engine") or "floating-3d"
    spec["layers"] = None
    lay = pipeline.layout_for(spec, eng, pipeline.screen_blocks(spec, loc, sid))
    raw = yaml.safe_load(pathlib.Path(a.campaign).read_text())
    raw["campaign"]["engine"] = eng
    raw["background"] = lay["background"]
    raw["layers"] = lay["layers"]
    out = pathlib.Path(a.out) if a.out else pathlib.Path(a.campaign).with_name(pathlib.Path(a.campaign).stem + f".{eng}.yaml")
    out.write_text(f"# Ejected from engine {eng}: edit the layers by hand. Units in references/creative-director.md\n"
                   + yaml.safe_dump(raw, sort_keys=False, allow_unicode=True, width=110))
    print(f"wrote {out} ({len(lay['layers'])} layers)")


def cmd_validate(a):
    root = pathlib.Path(a.out_dir)
    m = json.loads((root / "campaign-manifest.json").read_text())
    total = 0
    for r in m["renders"]:
        files = [pathlib.Path(e["file"]) for e in r["files"]]
        issues = pipeline.export_checks(files, r["size"][0], r["size"][1], r["panels"])
        for e in r["files"]:
            p = pathlib.Path(e["file"])
            if p.exists() and pipeline.sha(p) != e["sha256"]:
                issues.append(("warn", p.name, "changed since the render (hand-edited?)"))
        errs = sum(1 for i in issues if i[0] == "error")
        total += errs
        print(f"{r['locale']} {r['slot']}: {'PASS' if not errs else 'FAIL'}")
        print_issues(issues)
    return 1 if total else 0


def cmd_canvas(a):
    from studio import canvas
    rules = load_rules(a.campaign)
    spec, _ = load_checked(a.campaign, rules)
    return canvas.export(spec, rules, pathlib.Path(a.out), a.locale, a.slot, a.offline)


def cmd_canvas_link(a):
    from studio import canvas
    return canvas.link(pathlib.Path(a.out_dir))


def cmd_engines(_a):
    for k, v in engines.ENGINES.items():
        need = f"  needs: {'; '.join(v['needs'])}" if v["needs"] else ""
        print(f"{k:18} {v['pattern']}\n{'':18} type: {v['type']}. {v['mood']}{need}")


def cmd_presets(_a):
    for k, v in fonts.PRESETS.items():
        print(f"{k:22} {v['display']['family']} / {v['text']['family']}: {v['mood']}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("analyze"); p.add_argument("screens", nargs="+"); p.add_argument("--icon"); p.add_argument("--out")
    p = sub.add_parser("init"); p.add_argument("kit"); p.add_argument("--app", required=True)
    p.add_argument("--screens", required=True); p.add_argument("--icon"); p.add_argument("--panels", type=int, default=6)
    p.add_argument("--slot", default="iphone-di-large"); p.add_argument("--force", action="store_true")
    p = sub.add_parser("check"); p.add_argument("campaign")
    p = sub.add_parser("concepts"); p.add_argument("campaign"); p.add_argument("--engines")
    p.add_argument("--scale", type=float, default=0.3); p.add_argument("--locale"); p.add_argument("--slot")
    p.add_argument("--out"); p.add_argument("--offline", action="store_true")
    p = sub.add_parser("render"); p.add_argument("campaign"); p.add_argument("--engine")
    p.add_argument("--locale", action="append"); p.add_argument("--slot", action="append")
    p.add_argument("--panel", type=int); p.add_argument("--install"); p.add_argument("--out")
    p.add_argument("--offline", action="store_true")
    p = sub.add_parser("eject"); p.add_argument("campaign"); p.add_argument("--engine"); p.add_argument("--out")
    p = sub.add_parser("validate"); p.add_argument("out_dir")
    p = sub.add_parser("canvas"); p.add_argument("campaign"); p.add_argument("--out", required=True)
    p.add_argument("--locale"); p.add_argument("--slot"); p.add_argument("--offline", action="store_true")
    p = sub.add_parser("canvas-link"); p.add_argument("out_dir")
    sub.add_parser("engines"); sub.add_parser("presets")
    a = ap.parse_args(argv)
    try:
        return {"analyze": cmd_analyze, "init": cmd_init, "check": cmd_check, "concepts": cmd_concepts,
                "render": cmd_render, "eject": cmd_eject, "validate": cmd_validate, "canvas": cmd_canvas,
                "canvas-link": cmd_canvas_link, "engines": cmd_engines, "presets": cmd_presets}[a.cmd](a) or 0
    except S.SpecError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
