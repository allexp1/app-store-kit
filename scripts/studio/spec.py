"""campaign.yaml: load, fill defaults, validate.

The file keeps five things apart, so one can change without rewriting the others:
  screens     CONTENT  what the app really shows (real screenshots, per locale and device)
  storyboard  COPY     what each panel says, per locale, and which screen proves it
  design      TOKENS   palette, type, device, grain, safe areas (propagate to every panel)
  background / layers  LAYOUT + ARTWORK  where things go (generated by an engine, or written out by hand)
  campaign    EXPORT   panel count, slots, locales
"""
from __future__ import annotations

import copy
import json
import pathlib
import re

import yaml

from . import fonts

HEX = re.compile(r"^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
DEFAULT_PALETTE = {"bg": "#F4F1EA", "bg2": "#E6E0D4", "ink": "#16140F", "muted": "#6B665C",
                   "accent": "#FF5A36", "accent2": "#2D5BFF", "dark": "#121212", "light": "#FFFFFF"}
DEFAULT_DESIGN = {
    "palette": DEFAULT_PALETTE,
    "type": {"preset": "modern-tech"},
    "device": {"model": "iphone", "finish": "titanium", "shadow": "soft", "glare": 0.08, "focal": 2.6,
               "light": 315},
    "grain": 0.035,
    "safe": {"side": 0.07, "top": 0.05, "bottom": 0.035},
}
LAYER_TYPES = {"device", "card", "text", "display", "shape", "image", "glow", "icon"}
BG_TYPES = {"solid", "linear", "radial", "conic", "image", "panel"}
ROLES = ["hero", "value", "differentiator", "experience", "secondary", "closing", "feature", "proof"]

# Words that make a claim Apple or a reader would ask evidence for. A storyboard entry may carry
# `evidence:` (where the number comes from); without it these are errors, not style notes.
CLAIM_PATTERNS = [
    (r"(?i)(\bno\.?\s*1\b|#\s*1\b|\bnumber\s+one\b)", "a ranking"),
    (r"(?i)\b(best|leading|top[- ]rated|world'?s\s+(?:best|first)|most\s+popular)\b", "a superlative"),
    (r"(?i)\b(trusted|loved|used|chosen)\s+by\s+[\d.,]+\s*[km+]?", "a user count"),
    (r"(?i)\b[\d.,]+\s*[km]?\+?\s*(users|downloads|customers|travel+ers|members|reviews|ratings|people)\b", "a user count"),
    (r"(?i)\b(award|winner|winning)\b", "an award"),
    (r"[★⭐]|(?i:\b\d(\.\d)?\s*stars?\b|\brated\s+\d)", "a rating"),
    (r"(?i)\b\d+\s*%\s*(faster|better|more|less|cheaper)\b", "a performance figure"),
]
STORE_FORBIDDEN = [
    (r"(?i)editor'?s'?\s*choice|app of the day|game of the day|apple design award", "Apple recognitions are not allowed"),
    (r"(?i)\bhttps?://|www\.|\.(com|app|io)\b", "URLs are not allowed in store images"),
    (r"[$€£¥₪₽]\s?\d|\d\s?[$€£¥₪₽]|(?i:\bfree\s+trial\b|\b\d+\s*% off\b)", "prices and discounts are not allowed"),
    (r"©|\(c\)", "© marks are not allowed"),
    (r"(?i)google play|android|play store", "other platforms are not allowed"),
]


class SpecError(Exception):
    pass


def deep_merge(a: dict, b: dict) -> dict:
    out = copy.deepcopy(a)
    for k, v in (b or {}).items():
        out[k] = deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else copy.deepcopy(v)
    return out


def load(path) -> dict:
    p = pathlib.Path(path)
    if not p.exists():
        raise SpecError(f"{p}: not found")
    try:
        raw = yaml.safe_load(p.read_text()) or {}
    except yaml.YAMLError as e:
        raise SpecError(f"{p}: not valid YAML: {e}") from e
    if not isinstance(raw, dict):
        raise SpecError(f"{p}: the top level must be a mapping")
    spec = normalize(raw)
    spec["_base"] = str(p.parent.resolve())
    spec["_path"] = str(p.resolve())
    return spec


def normalize(raw: dict) -> dict:
    spec = copy.deepcopy(raw)
    c = spec.setdefault("campaign", {})
    c.setdefault("name", (spec.get("app") or {}).get("name", "Campaign"))
    sb = spec.get("storyboard") or []
    c.setdefault("panels", len(sb) or 6)
    c.setdefault("locales", ["en-US"])
    c.setdefault("primary_locale", c["locales"][0])
    c.setdefault("slots", ["iphone-di-large"])
    c.setdefault("seed", 1)
    c.setdefault("rtl_flow", "mirror")
    c.setdefault("mockup_only", False)
    spec["design"] = deep_merge(DEFAULT_DESIGN, spec.get("design") or {})
    spec.setdefault("screens", {})
    spec.setdefault("storyboard", [])
    spec.setdefault("artwork", {})
    for i, p in enumerate(spec["storyboard"], 1):
        p.setdefault("id", f"p{i}")
        p.setdefault("role", ROLES[i - 1] if i <= len(ROLES) else "feature")
    return spec


def text_for(value, locale: str, primary: str):
    """A copy value: a string (all locales) or {locale: text, '*': text}. Returns (text, from_locale)."""
    if value is None:
        return None, None
    if isinstance(value, str):
        return value, "*"
    for k in (locale, fonts.lang(locale), "*"):
        if k in value:
            return value[k], k
    if primary in value:
        return value[primary], primary
    return None, None


def screen_path(spec: dict, sid: str, locale: str, slot: str):
    """Resolve a screen id to a file for this locale and slot. Returns (path, localized: bool)."""
    s = spec["screens"].get(sid)
    if s is None:
        return None, False
    if isinstance(s, str):
        s = {"file": s}
    fam = "ipad" if slot.startswith("ipad") else "iphone"
    tpl = s.get(slot) or s.get(fam) or s.get("file")
    if not tpl:
        return None, False
    base = pathlib.Path(spec["_base"])
    p = base / str(tpl).format(locale=locale, lang=fonts.lang(locale))
    if p.exists():
        return p, "{locale}" in str(tpl) or "{lang}" in str(tpl)
    if "{locale}" in str(tpl) or "{lang}" in str(tpl):
        primary = spec["campaign"]["primary_locale"]
        q = base / str(tpl).format(locale=primary, lang=fonts.lang(primary))
        if q.exists():
            return q, False
    return p, False


def slot_size(slot, rules: dict):
    if isinstance(slot, dict):
        return slot["id"], int(slot["width"]), int(slot["height"])
    s = rules["screenshots"]["slots"].get(slot)
    if not s:
        raise SpecError(f"unknown slot {slot!r}; one of {', '.join(rules['screenshots']['slots'])}")
    # the largest accepted size: Apple scales down, never up
    w, h = max(s["sizes"], key=lambda wh: wh[0] * wh[1])
    return slot, int(w), int(h)


def check_copy(text: str, where: str, evidence: str | None, issues: list):
    if not text:
        return
    plain = text.replace("**", "")
    for pat, why in STORE_FORBIDDEN:
        if re.search(pat, plain):
            issues.append(("error", where, f"{why}: {plain!r}"))
    for pat, what in CLAIM_PATTERNS:
        if re.search(pat, plain):
            if evidence:
                issues.append(("note", where, f"{what} with evidence ({evidence}): {plain!r}"))
            elif what == "a superlative":
                issues.append(("warn", where, f"{what}: {plain!r}. Fine as everyday language ('your best "
                                              "run'); as a claim about the app it needs evidence"))
            else:
                issues.append(("error", where, f"{what} without `evidence:`: {plain!r}. Never invent numbers, "
                                                "ratings or awards; add the source or drop the claim"))


def validate(spec: dict, rules: dict) -> list:
    """Return [(level, where, message)] for the whole campaign. Errors stop a render."""
    issues = []
    c = spec["campaign"]
    n = c["panels"]
    if not isinstance(n, int) or not 1 <= n <= 10:
        issues.append(("error", "campaign.panels", f"must be 1–10 (App Store sets hold up to 10), got {n!r}"))
        return issues
    sb = spec["storyboard"]
    if len(sb) != n:
        issues.append(("error", "storyboard", f"{len(sb)} entries for {n} panels; one entry per panel"))
    for s in c["slots"]:
        try:
            slot_size(s, rules)
        except SpecError as e:
            issues.append(("error", "campaign.slots", str(e)))
    for k, v in spec["design"]["palette"].items():
        if not isinstance(v, str) or not HEX.match(v):
            issues.append(("error", f"design.palette.{k}", f"not a #hex colour: {v!r}"))
    if spec["design"]["type"].get("preset", "modern-tech") not in fonts.PRESETS:
        issues.append(("error", "design.type.preset", f"unknown preset {spec['design']['type']['preset']!r}; one of {', '.join(fonts.PRESETS)}"))
    if c["rtl_flow"] not in ("mirror", "keep"):
        issues.append(("error", "campaign.rtl_flow", "mirror or keep"))
    used = set()
    for i, p in enumerate(sb, 1):
        where = f"storyboard[{i}] {p.get('id')}"
        for sid in [p.get("screen")] + list(p.get("screens") or []):
            if not sid:
                continue
            used.add(sid)
            if sid not in spec["screens"]:
                issues.append(("error", where, f"screen {sid!r} is not defined under screens:"))
        if not p.get("screen") and not p.get("screens") and not p.get("no_screen"):
            issues.append(("warn", where, "no screen: every panel should show real UI (set no_screen: true "
                                          "for a deliberate type-only panel)"))
        bad = False
        for field in ("headline", "sub", "kicker"):
            v = p.get(field)
            vals = [v] if not isinstance(v, dict) else list(v.values())
            if any(x is not None and not isinstance(x, str) for x in vals):
                issues.append(("error", where, f"{field} is not text: {v!r}. YAML reads an unquoted [..] as a "
                                               "list; put the copy in quotes"))
                bad = True
        if bad:
            continue
        for loc in c["locales"]:
            for field in ("headline", "sub", "kicker"):
                t, src = text_for(p.get(field), loc, c["primary_locale"])
                if field == "headline" and t is None:
                    issues.append(("error", where, f"no headline for {loc}"))
                if t is None:
                    continue
                if src not in (loc, fonts.lang(loc), "*") and loc != c["primary_locale"]:
                    issues.append(("warn", where, f"{field} for {loc} falls back to {src}: untranslated"))
                check_copy(t, f"{where} {field} [{loc}]", p.get("evidence"), issues)
                if field == "headline":
                    words = len(re.findall(r"\w+", t.replace("**", "")))
                    if words > 9:
                        issues.append(("warn", where, f"headline [{loc}] has {words} words; 3–8 read at store size"))
    if not c["mockup_only"]:
        for sid in sorted(used):
            for loc in c["locales"]:
                for slot in c["slots"]:
                    sl = slot if isinstance(slot, str) else slot["id"]
                    p, localized = screen_path(spec, sid, loc, sl)
                    if p is None or not p.exists():
                        issues.append(("error", f"screens.{sid}", f"{loc}/{sl}: file {p} not found (real "
                                       "screenshots are required; set campaign.mockup_only: true only for "
                                       "concepts the owner asked for)"))
                    elif loc != c["primary_locale"] and not localized:
                        issues.append(("warn", f"screens.{sid}", f"{loc}: uses the {c['primary_locale']} "
                                       "screenshot; translated copy over untranslated UI must be pointed out"))
    for name, a in (spec.get("artwork") or {}).items():
        f = pathlib.Path(spec["_base"]) / str(a.get("file", ""))
        if not a.get("file") or not f.exists():
            issues.append(("error", f"artwork.{name}", f"file {f} not found"))
        if not a.get("source") or not a.get("licence"):
            issues.append(("error", f"artwork.{name}", "needs source: and licence: (provenance); generated "
                                                        "art also says generated: true and the tool"))
    for j, L in enumerate(spec.get("layers") or []):
        t = L.get("type")
        if t not in LAYER_TYPES:
            issues.append(("error", f"layers[{j}]", f"type {t!r} is not one of {', '.join(sorted(LAYER_TYPES))}"))
        if t == "text" and not 1 <= int(L.get("panel", 0)) <= n:
            issues.append(("error", f"layers[{j}]", f"text panel {L.get('panel')!r} is outside 1–{n}"))
        if t in ("device", "card") and L.get("screen") not in spec["screens"]:
            issues.append(("error", f"layers[{j}]", f"screen {L.get('screen')!r} is not defined"))
        if t == "image" and L.get("art") not in (spec.get("artwork") or {}):
            issues.append(("error", f"layers[{j}]", f"art {L.get('art')!r} is not defined under artwork:"))
    for j, B in enumerate(spec.get("background") or []):
        if B.get("type") not in BG_TYPES:
            issues.append(("error", f"background[{j}]", f"type {B.get('type')!r} is not one of {', '.join(sorted(BG_TYPES))}"))
    return issues


def tokens(spec: dict) -> dict:
    """design-tokens.json: the campaign's design system in one place."""
    d = spec["design"]
    return {"name": spec["campaign"]["name"], "palette": d["palette"], "type": d["type"], "device": d["device"],
            "grain": d["grain"], "safe": d["safe"], "engine": spec["campaign"].get("engine"),
            "units": {"x": "panels from the left edge of panel 1", "y": "fraction of panel height",
                      "w": "u = min(panel width, panel height / 2.17)", "size": "u"}}


def dump(spec: dict) -> str:
    clean = {k: v for k, v in spec.items() if not k.startswith("_")}
    return yaml.safe_dump(clean, sort_keys=False, allow_unicode=True, width=110)


def as_json(spec: dict) -> str:
    return json.dumps({k: v for k, v in spec.items() if not k.startswith("_")}, indent=2, ensure_ascii=False)
